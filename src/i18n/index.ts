/**
 * Traductions du site public : français (par défaut) et arabe (/ar/…, dir="rtl").
 * Toutes les chaînes affichées passent par ce dictionnaire ; l'espace admin reste en français.
 */
export const LANGS = { fr: { dir: 'ltr', label: 'Français', court: 'FR' }, ar: { dir: 'rtl', label: 'العربية', court: 'عربي' } } as const;
export type Lang = keyof typeof LANGS;

export const dirOf = (lang: Lang) => LANGS[lang].dir;

/** Chemin localisé : '/don' → '/ar/don' */
export function lien(path: string, lang: Lang): string {
  if (lang === 'fr') return path;
  return path === '/' ? '/ar' : `/ar${path}`;
}

/** Chemin équivalent dans l'autre langue */
export function cheminAutreLangue(pathname: string, lang: Lang): string {
  const sansAr = pathname.replace(/^\/ar(?=\/|$)/, '') || '/';
  return lang === 'fr' ? lien(sansAr, 'ar') : sansAr;
}

/** Langue déduite de l'URL (pour les îlots) */
export const langDepuisChemin = (pathname: string): Lang => (/^\/ar(\/|$)/.test(pathname) ? 'ar' : 'fr');

